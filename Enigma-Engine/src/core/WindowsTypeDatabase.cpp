class WindowsTypeDatabase : public TypeDatabase {
public:
    bool getFunctionType(const std::string& funcName,
                         std::string& returnType,
                         std::vector<std::string>& paramTypes) const override {
        // Check base table first
        const auto& table = getTypeTable();
        auto it = table.find(funcName);
        if (it != table.end()) {
            returnType = it->second.returnType;
            paramTypes.clear();
            for (const char* p : it->second.paramTypes)
                paramTypes.push_back(p);
            return true;
        }
        // Check auto-generated extended table as fallback
        const auto& ext = getSigGenTable();
        auto eit = ext.find(funcName);
        if (eit == ext.end()) return false;
        returnType = eit->second.returnType;
        paramTypes.clear();
        for (const char* p : eit->second.paramTypes)
            paramTypes.push_back(p);
        return true;
    }

    bool isNoReturn(const std::string& funcName) const override {
        const auto& table = getNoReturnTable();
        return table.find(funcName) != table.end();
    }

    bool isVariadic(const std::string& funcName) const override {
        const auto& table = getVariadicTable();
        return table.find(funcName) != table.end();
    }

    std::string getPlatformName() const override {
        return "Windows";
    }
};

std::unique_ptr<TypeDatabase> createWindowsTypeDatabase() {
    return std::make_unique<WindowsTypeDatabase>();
}

