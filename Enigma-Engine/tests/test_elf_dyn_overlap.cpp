int main() {
    std::cout << "=== ELF DYN Overlap Test ===" << std::endl;

    const std::string tmpPath = "test_elf_dyn_overlap_tmp.elf";
    {
        std::ofstream out(tmpPath, std::ios::binary);
        TEST("tmp elf written", (bool)out);
        out.write(reinterpret_cast<const char*>(kDynOverlapElf), sizeof(kDynOverlapElf));
    }

    auto loader = ghidra::createLoader();
    TEST("loader created", (bool)loader);
    TEST("dyn elf loads", loader && loader->load(tmpPath));
    if (!loader) { std::remove(tmpPath.c_str()); return 1; }

    auto* prog = new ghidra::ProgramDB("dynoverlap", nullptr, nullptr);
    auto* af = dynamic_cast<ghidra::ProgramAddressFactory*>(prog->getAddressFactory());
    TEST("addr factory present", af != nullptr);
    if (!af) { delete prog; std::remove(tmpPath.c_str()); return 1; }
    auto* ram = new ghidra::GenericAddressSpace("ram", 64,
        ghidra::AddressSpace::TYPE_RAM, 1);
    af->addAddressSpace(ram);
    af->setDefaultSpace(ram);

    bool populated = false;
    try {
        populated = loader->populateProgram(prog);
    } catch (const std::exception& e) {
        std::cout << "populate threw: " << e.what() << std::endl;
    }
    TEST("populate does not throw", populated);

    // No two blocks may overlap: getBlock() resolves ambiguously otherwise.
    bool disjoint = true;
    if (auto* mem = prog->getMemory()) {
        auto blocks = mem->getBlocks();
        for (size_t i = 0; i < blocks.size() && disjoint; ++i) {
            if (!blocks[i]) continue;
            uint64_t a0 = blocks[i]->getStart().getUnsignedOffset();
            uint64_t a1 = a0 + blocks[i]->getSize();
            for (size_t j = i + 1; j < blocks.size(); ++j) {
                if (!blocks[j]) continue;
                uint64_t b0 = blocks[j]->getStart().getUnsignedOffset();
                uint64_t b1 = b0 + blocks[j]->getSize();
                if (a0 < b1 && b0 < a1) {
                    std::cout << "overlap: [" << std::hex << a0 << "," << a1
                              << ") vs [" << b0 << "," << b1 << ")" << std::dec << std::endl;
                    disjoint = false;
                }
            }
        }
        TEST("blocks disjoint", disjoint);

        // .text content landed in its own executable block.
        uint8_t buf[4] = {0, 0, 0, 0};
        int got = 0;
        try {
            got = mem->getBytes(af->oldGetAddressFromLong(0x100), buf, 4);
        } catch (...) {}
        TEST("text readable", got == 4);
        TEST("text content", buf[0] == 0xF8 && buf[1] == 0xFF && buf[2] == 0xBD && buf[3] == 0x27);
        auto* tb = mem->getBlock(af->oldGetAddressFromLong(0x100));
        TEST("text block executable", tb && tb->isExecute());
    }

    // main() from the static symtab became a function.
    bool sawMain = false;
    if (auto* fm = prog->getFunctionManager()) {
        ghidra::FunctionIterator fit = fm->getFunctions(true);
        while (fit.hasNext()) {
            auto* f = fit.next();
            if (f && f->getEntryPoint().getUnsignedOffset() == 0x100) sawMain = true;
        }
    }
    TEST("main func", sawMain);

    // Plain MIPS32: no spurious MIPS16 ranges.
    TEST("no mips16 ranges", prog->getMips16Ranges().empty());

    delete prog;
    std::remove(tmpPath.c_str());
    std::cout << "\n=== Summary ===\n" << passed << "/" << total << " tests passed" << std::endl;
    return (passed == total) ? 0 : 1;
}
