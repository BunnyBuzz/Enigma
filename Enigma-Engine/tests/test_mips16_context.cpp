int main() {
    std::cout << "=== MIPS16e Context Test (GP-6766) ===" << std::endl;

    const std::string tmpPath = "test_mips16_context_tmp.elf";
    {
        std::ofstream out(tmpPath, std::ios::binary);
        TEST("tmp elf written", (bool)out);
        out.write(reinterpret_cast<const char*>(kMips16TestElf), sizeof(kMips16TestElf));
    }

    TEST("library init", ghidra::DecompInterface::initializeLibrary());

    auto loader = ghidra::createLoader();
    TEST("loader created", (bool)loader);
    TEST("elf loads", loader && loader->load(tmpPath));
    if (!loader) { std::remove(tmpPath.c_str()); return 1; }
    TEST("arch is MIPS", loader->getArchitecture() == "MIPS");

    auto* prog = new ghidra::ProgramDB("mips16test", nullptr, nullptr);
    auto* af = dynamic_cast<ghidra::ProgramAddressFactory*>(prog->getAddressFactory());
    TEST("addr factory present", af != nullptr);
    if (!af) { delete prog; std::remove(tmpPath.c_str()); return 1; }
    auto* ram = new ghidra::GenericAddressSpace("ram", 64,
        ghidra::AddressSpace::TYPE_RAM, 1);
    af->addAddressSpace(ram);
    af->setDefaultSpace(ram);

    TEST("populate ok", loader->populateProgram(prog));
    TEST("language is MIPS", prog->getLanguageID().getIdAsString().find("MIPS") != std::string::npos);

    // STO_MIPS16 symbol -> exactly one decode range [0x400014, 0x400020).
    const auto& ranges = prog->getMips16Ranges();
    TEST("one mips16 range", ranges.size() == 1);
    if (!ranges.empty()) {
        TEST("range start", ranges[0].first == 0x400014);
        TEST("range end", ranges[0].second == 0x400020);
    }

    // Functions from static symtab.
    bool sawStart = false, sawM16 = false, sawPlain = false;
    if (auto* fm = prog->getFunctionManager()) {
        ghidra::FunctionIterator fit = fm->getFunctions(true);
        while (fit.hasNext()) {
            auto* f = fit.next();
            if (!f) continue;
            uint64_t e = f->getEntryPoint().getUnsignedOffset();
            if (e == 0x400000) sawStart = true;
            if (e == 0x400014) sawM16 = true;
            if (e == 0x400020) sawPlain = true;
        }
    }
    TEST("entry func", sawStart);
    TEST("mips16 func", sawM16);
    TEST("plain func", sawPlain);

    ghidra::DecompInterface di;
    TEST("decomp opens", di.openProgram(prog));
    if (di.isOpen()) {
        TEST("mips32 len 4 @400000", di.instructionLengthAt(0x400000) == 4);
        TEST("mips32 len 4 @400004", di.instructionLengthAt(0x400004) == 4);
        TEST("mips16 len 2 @400014", di.instructionLengthAt(0x400014) == 2);
        TEST("mips16 len 2 @400016", di.instructionLengthAt(0x400016) == 2);
        TEST("mips16 len 2 @400018", di.instructionLengthAt(0x400018) == 2);
        TEST("mips16 len 2 @40001A", di.instructionLengthAt(0x40001A) == 2);
        TEST("mips16 len 2 @40001C", di.instructionLengthAt(0x40001C) == 2);
        TEST("mips16 len 2 @40001E", di.instructionLengthAt(0x40001E) == 2);
        TEST("mips32 len 4 @400020", di.instructionLengthAt(0x400020) == 4);
        std::string d;
        try { d = di.disassembleAt(af->oldGetAddressFromLong(0x40001E), 1); } catch (...) {}
        TEST("jrc ra decoded", d.find("jrc") != std::string::npos);
    }

    // Native pipeline: DisassemblyAnalyzer follows the same ranges via
    // Capstone microMIPS mode. Assert stepping lengths only (mnemonics are
    // microMIPS-flavored by toolchain limitation, see note at top).
    {
        ghidra::DisassemblyAnalyzer da;
        ghidra::AddressSet whole(
            af->oldGetAddressFromLong(0x400000),
            af->oldGetAddressFromLong(0x400027));
        ghidra::MessageLog log;
        TEST("analyzer runs", da.added(prog, whole, &ghidra::getDummyMonitor(), log));
        auto* listing = prog->getListing();
        auto lenAt = [&](uint64_t a) -> int {
            auto* ci = listing ? listing->getInstructionAt(af->oldGetAddressFromLong(a)) : nullptr;
            return ci ? ci->getLength() : -1;
        };
        TEST("native len 4 @400000", lenAt(0x400000) == 4);
        TEST("native len 2 @400014", lenAt(0x400014) == 2);
        TEST("native len 2 @400016", lenAt(0x400016) == 2);
        TEST("native len 2 @400018", lenAt(0x400018) == 2);
        TEST("native len 2 @40001A", lenAt(0x40001A) == 2);
        TEST("native len 2 @40001C", lenAt(0x40001C) == 2);
        TEST("native len 2 @40001E", lenAt(0x40001E) == 2);
        TEST("native len 4 @400020", lenAt(0x400020) == 4);
    }

    delete prog;
    std::remove(tmpPath.c_str());
    std::cout << "\n=== Summary ===\n" << passed << "/" << total << " tests passed" << std::endl;
    return (passed == total) ? 0 : 1;
}
