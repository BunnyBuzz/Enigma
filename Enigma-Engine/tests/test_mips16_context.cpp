// GP-6766 MIPS16e end-to-end: STO_MIPS16 ELF symbol -> loader range ->
// SLEIGH ISA_MODE context -> 2-byte instruction lengths.
// The embedded ELF is a minimal MIPS32-LE ET_EXEC (see craft_mips16.py):
//   0x400000 _start:     addiu/jal/nop/j ./nop        (MIPS32, len 4)
//   0x400014 mips16code: 5x addiu-pattern + jrc ra    (MIPS16, len 2,
//                        STO_MIPS16 st_other + st_size 12)
//   0x400020 plainfunc:  jr ra/nop                    (MIPS32, len 4)
// NOTE on the native section below: this Capstone has no MIPS16e mode
// (0x10 is microMIPS), so the native analyzer rows have correct 2-byte
// stepping but microMIPS-flavored mnemonics (e.g. addu16, not addiu).
// Only lengths are asserted natively; names are asserted on the SLEIGH
// side, which is the semantically correct MIPS16e decode.
